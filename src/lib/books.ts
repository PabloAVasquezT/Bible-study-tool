// The 66 books of the Protestant canon, in order, identified by their USFM codes.

export const OLD_TESTAMENT = [
  'GEN', 'EXO', 'LEV', 'NUM', 'DEU', 'JOS', 'JDG', 'RUT', '1SA', '2SA',
  '1KI', '2KI', '1CH', '2CH', 'EZR', 'NEH', 'EST', 'JOB', 'PSA', 'PRO',
  'ECC', 'SNG', 'ISA', 'JER', 'LAM', 'EZK', 'DAN', 'HOS', 'JOL', 'AMO',
  'OBA', 'JON', 'MIC', 'NAM', 'HAB', 'ZEP', 'HAG', 'ZEC', 'MAL'
] as const

export const NEW_TESTAMENT = [
  'MAT', 'MRK', 'LUK', 'JHN', 'ACT', 'ROM', '1CO', '2CO', 'GAL', 'EPH',
  'PHP', 'COL', '1TH', '2TH', '1TI', '2TI', 'TIT', 'PHM', 'HEB', 'JAS',
  '1PE', '2PE', '1JN', '2JN', '3JN', 'JUD', 'REV'
] as const

export const BOOK_IDS = [...OLD_TESTAMENT, ...NEW_TESTAMENT] as const

export type BookId = (typeof BOOK_IDS)[number]

export function isBookId(value: string): value is BookId {
  return (BOOK_IDS as readonly string[]).includes(value)
}
